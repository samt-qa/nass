#!/usr/bin/env node
// Generates spec/tables.json from tools/tables.src.json.
// Usage: node tools/gen-tables.mjs          -> write spec/tables.json
//        node tools/gen-tables.mjs --check  -> exit 1 if spec/tables.json is stale (CI)
//
// NFKC is used here, at build time, one character at a time, only to derive the
// presentation-form table. Runtime code must never call NFKC (SPEC C1/C4).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = join(root, "tools", "tables.src.json");
const outPath = join(root, "spec", "tables.json");
const src = JSON.parse(readFileSync(srcPath, "utf8"));

if (process.versions.unicode !== src.unicodeVersion) {
  console.error(`Unicode mismatch: Node has ${process.versions.unicode}, source pins ${src.unicodeVersion}.`);
  process.exit(2);
}

const cp = (h) => parseInt(h, 16);
const hex = (n) => n.toString(16).toUpperCase().padStart(4, "0");
const str = (h) => String.fromCodePoint(cp(h));

/** Expand ["0600", ["0610","061A"], ...] to sorted unique hex list. */
function expand(list) {
  const out = new Set();
  for (const item of list) {
    if (Array.isArray(item)) {
      for (let c = cp(item[0]); c <= cp(item[1]); c++) out.add(c);
    } else out.add(cp(item));
  }
  return [...out].sort((a, b) => a - b).map(hex);
}

/** Collapse a sorted hex list back to compact ranges for readability. */
function compress(list) {
  const out = [];
  for (const h of list) {
    const c = cp(h);
    const last = out[out.length - 1];
    if (last && cp(last[1]) === c - 1) last[1] = h;
    else out.push([h, h]);
  }
  return out.map(([a, b]) => (a === b ? a : [a, b]));
}

const isAssigned = (ch) => !/\p{Cn}/u.test(ch);
const deferred = new Set(expand(src.presentationDeferredToSearch));

const presentation = {};
const presentationSearch = {};
for (const h of expand(src.presentationRanges)) {
  const ch = str(h);
  if (!isAssigned(ch)) continue;
  // Strip only the single leading space NFKC adds before isolated harakat (FE70.., FC5E..).
  const mapped = ch.normalize("NFKC").replace(/^ /, "");
  if (mapped === ch) continue; // no compatibility decomposition; may be in manualSearch
  const target = [...mapped].map((c) => hex(c.codePointAt(0))).join(" ");
  (deferred.has(h) ? presentationSearch : presentation)[h] = target;
}

// Ligatures with no NFKC decomposition: hand-written expansions from the source file.
for (const [h, text] of Object.entries(src.presentationManual)) {
  if (h.startsWith("$")) continue;
  presentationSearch[h] = [...text].map((c) => hex(c.codePointAt(0))).join(" ");
}
const pending = [...deferred].filter((h) => isAssigned(str(h)) && !(h in presentationSearch));

// Sanity: every mark/letter in the maps must be assigned in this Unicode version.
for (const h of [...expand(src.marks), ...Object.keys(src.letterMap)]) {
  if (!isAssigned(str(h))) throw new Error(`Unassigned code point in source: U+${h}`);
}

const out = {
  $comment: "GENERATED by tools/gen-tables.mjs from tools/tables.src.json. Do not edit by hand.",
  unicodeVersion: src.unicodeVersion,
  invisibleAlways: compress(expand(src.invisibleAlways)),
  invisibleNearArabic: compress(expand(src.invisibleNearArabic)),
  tatweel: expand(src.tatweel),
  arabicRanges: src.arabicRanges,
  presentation,
  presentationSearch,
  presentationSearchPending: pending,
  marks: compress(expand(src.marks)),
  letterMap: src.letterMap,
  digitMap: src.digitMap,
  digitSeparators: src.digitSeparators,
  extraSeparators: expand(src.extraSeparators),
  looseMap: src.looseMap,
  looseRemove: expand(src.looseRemove),
  honorificsWritten: src.honorificsWritten,
  names: src.names,
  stats: {
    presentation: Object.keys(presentation).length,
    presentationSearch: Object.keys(presentationSearch).length,
    marks: expand(src.marks).length,
  },
};

const json = JSON.stringify(out, null, 2) + "\n";

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== json) {
    console.error("spec/tables.json is stale. Run: node tools/gen-tables.mjs");
    process.exit(1);
  }
  console.log("spec/tables.json is up to date.");
} else {
  writeFileSync(outPath, json);
  console.log(`Wrote spec/tables.json`, out.stats);
}
